// Transformation call scheduler (contactModal): calendar → time slot → details.
// The chosen slot travels in "comments" via window.schedMeeting.
// ──────────────────────────────────────────────────────────────
(function initScheduler() {
    const pick = document.getElementById('schedPick');
    if (!pick) return;
    const details = document.getElementById('schedDetails');
    const daysEl = document.getElementById('schedDays');
    const weekdaysEl = document.getElementById('schedWeekdays');
    const monthEl = document.getElementById('schedMonth');
    const slotList = document.getElementById('schedSlotList');
    const slotsTitle = document.getElementById('schedSlotsTitle');
    const chosen = document.getElementById('schedChosen');
    const chosenText = document.getElementById('schedChosenText');
    const SLOTS = ['09:30', '10:00', '10:30', '11:00', '11:30', '12:00', '13:30', '14:00', '14:30', '15:00', '15:30', '16:00', '16:30', '17:00'];
    const MAX_DAYS_AHEAD = 60;

    const today = new Date(); today.setHours(0, 0, 0, 0);
    const first = new Date(today); first.setDate(first.getDate() + 1);
    const last = new Date(today); last.setDate(last.getDate() + MAX_DAYS_AHEAD);
    let view = new Date(first.getFullYear(), first.getMonth(), 1);
    let selDate = null;
    let selTime = null;

    const locale = () => (currentLanguage === 'tr' ? 'tr-TR' : 'en-GB');
    const fmt = (d, o) => new Intl.DateTimeFormat(locale(), o).format(d);
    const isOpenDay = (d) => d >= first && d <= last && d.getDay() !== 0 && d.getDay() !== 6;
    const sameDay = (a, b) => Boolean(a && b && a.getTime() === b.getTime());
    const t = (tr, en) => (currentLanguage === 'tr' ? tr : en);
    const longLabel = () => fmt(selDate, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }) + ', ' + selTime;
    const meetingLine = () => t('GÖRÜŞME TALEBİ: ', 'MEETING REQUEST: ') + longLabel() + t(' (TSİ)', ' (GMT+3)');

    function renderWeekdays() {
        const monday = new Date(2024, 0, 1);
        weekdaysEl.innerHTML = '';
        for (let i = 0; i < 7; i += 1) {
            const d = new Date(monday); d.setDate(monday.getDate() + i);
            const span = document.createElement('span');
            span.textContent = fmt(d, { weekday: 'short' }).replace('.', '');
            weekdaysEl.appendChild(span);
        }
    }

    function renderCalendar() {
        monthEl.textContent = fmt(view, { month: 'long', year: 'numeric' });
        daysEl.innerHTML = '';
        const offset = (new Date(view.getFullYear(), view.getMonth(), 1).getDay() + 6) % 7;
        for (let i = 0; i < offset; i += 1) daysEl.appendChild(document.createElement('span'));
        const count = new Date(view.getFullYear(), view.getMonth() + 1, 0).getDate();
        for (let n = 1; n <= count; n += 1) {
            const d = new Date(view.getFullYear(), view.getMonth(), n);
            const btn = document.createElement('button');
            btn.type = 'button';
            btn.textContent = String(n);
            btn.className = 'sched-day';
            if (sameDay(d, today)) btn.classList.add('is-today');
            if (sameDay(d, selDate)) btn.classList.add('is-selected');
            if (!isOpenDay(d)) {
                btn.disabled = true;
            } else {
                btn.classList.add('is-open');
                btn.addEventListener('click', () => { selDate = d; selTime = null; renderCalendar(); renderSlots(); });
            }
            daysEl.appendChild(btn);
        }
        document.getElementById('schedPrev').disabled = view <= new Date(first.getFullYear(), first.getMonth(), 1);
        document.getElementById('schedNext').disabled = view >= new Date(last.getFullYear(), last.getMonth(), 1);
    }

    function renderSlots() {
        slotList.innerHTML = '';
        if (!selDate) {
            slotsTitle.textContent = t('Bir gün seçin', 'Pick a day');
            return;
        }
        slotsTitle.textContent = fmt(selDate, { weekday: 'long', day: 'numeric', month: 'long' });
        SLOTS.forEach((time) => {
            const btn = document.createElement('button');
            btn.type = 'button';
            btn.className = 'sched-slot';
            btn.textContent = time;
            btn.addEventListener('click', () => choose(time));
            slotList.appendChild(btn);
        });
    }

    function choose(time) {
        selTime = time;
        window.schedMeeting = meetingLine();
        chosenText.textContent = longLabel();
        chosen.hidden = false;
        showDetails(true);
    }

    function showDetails(on) {
        pick.hidden = on;
        details.hidden = !on;
        if (on) {
            const field = details.querySelector('input:not([type="hidden"])');
            if (field) setTimeout(() => field.focus(), 30);
        }
    }

    function refresh() {
        renderWeekdays();
        renderCalendar();
        renderSlots();
        if (selTime) {
            chosenText.textContent = longLabel();
            window.schedMeeting = meetingLine();
        }
    }

    function reset() {
        selDate = null;
        selTime = null;
        window.schedMeeting = '';
        chosen.hidden = true;
        view = new Date(first.getFullYear(), first.getMonth(), 1);
        showDetails(false);
        refresh();
    }

    document.getElementById('schedPrev').addEventListener('click', () => { view = new Date(view.getFullYear(), view.getMonth() - 1, 1); renderCalendar(); });
    document.getElementById('schedNext').addEventListener('click', () => { view = new Date(view.getFullYear(), view.getMonth() + 1, 1); renderCalendar(); });
    document.getElementById('schedBack').addEventListener('click', () => showDetails(false));
    document.getElementById('schedSkip').addEventListener('click', () => {
        selTime = null;
        window.schedMeeting = '';
        chosen.hidden = true;
        showDetails(true);
    });
    document.addEventListener('click', (event) => {
        if (event.target.closest('[data-modal-open="contactModal"]')) reset();
    });
    document.querySelectorAll('.lang-btn').forEach((btn) => btn.addEventListener('click', () => setTimeout(refresh, 0)));
    reset();
})();

// Approach flow: steps auto-advance when the progress bar finishes; click to jump.
(function initApproachFlow() {
    const root = document.getElementById('flow');
    if (!root) return;
    const steps = Array.from(root.querySelectorAll('.flow-step'));
    const figs = Array.from(root.querySelectorAll('.flow-fig'));
    let index = 0;

    function activate(next) {
        index = (next + steps.length) % steps.length;
        steps.forEach((step, i) => {
            const on = i === index;
            step.classList.remove('is-active');
            if (on) {
                // force the progress animation to restart
                void step.offsetWidth;
                step.classList.add('is-active');
            }
        });
        figs.forEach((fig, i) => fig.classList.toggle('is-active', i === index));
    }

    steps.forEach((step, i) => {
        step.querySelector('.flow-title').addEventListener('click', () => activate(i));
        step.querySelector('.flow-bar').addEventListener('animationend', () => {
            if (i === index) activate(index + 1);
        });
    });

    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        root.querySelectorAll('.flow-bar').forEach((bar) => { bar.style.display = 'none'; });
    }
})();

