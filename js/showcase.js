(function initHeroCountUp() {
    const numbers = Array.from(document.querySelectorAll('.hero-stats [data-count]'));
    if (!numbers.length || !('IntersectionObserver' in window)) return;
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    // Start from zero right away so the final value never flashes first
    numbers.forEach((el) => { el.textContent = '0'; });

    function run(el) {
        const target = Number(el.getAttribute('data-count'));
        const start = performance.now();
        const duration = 1400;
        function frame(now) {
            const progress = Math.min(1, (now - start) / duration);
            const eased = 1 - Math.pow(1 - progress, 3);
            el.textContent = String(Math.round(target * eased));
            if (progress < 1) requestAnimationFrame(frame);
        }
        el.textContent = '0';
        requestAnimationFrame(frame);
    }

    const observer = new IntersectionObserver(function (entries) {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            run(entry.target);
            observer.unobserve(entry.target);
        });
    }, { threshold: 0.6 });
    numbers.forEach((el) => observer.observe(el));
})();
