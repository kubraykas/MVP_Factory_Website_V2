function initializeShowcaseCarousel() {
    const slides = Array.from(document.querySelectorAll('.carousel-slide'));
    const dots = Array.from(document.querySelectorAll('.dot'));
    if (!slides.length || !dots.length) return;

    let currentSlide = 0;

    function showSlide(index) {
        if (index >= slides.length) {
            currentSlide = 0;
        } else if (index < 0) {
            currentSlide = slides.length - 1;
        } else {
            currentSlide = index;
        }

        slides.forEach((slide, slideIndex) => {
            slide.classList.toggle('active', slideIndex === currentSlide);
        });

        dots.forEach((dot, dotIndex) => {
            dot.classList.toggle('active', dotIndex === currentSlide);
        });
    }

    document.querySelectorAll('[data-carousel-action]').forEach((button) => {
        button.addEventListener('click', function () {
            const action = button.getAttribute('data-carousel-action');
            showSlide(currentSlide + (action === 'prev' ? -1 : 1));
        });
    });

    dots.forEach((dot) => {
        dot.addEventListener('click', function () {
            const targetIndex = Number(dot.getAttribute('data-carousel-dot'));
            if (!Number.isNaN(targetIndex)) {
                showSlide(targetIndex);
            }
        });
    });

    showSlide(0);
    window.setInterval(function () {
        showSlide(currentSlide + 1);
    }, 3000);
}

