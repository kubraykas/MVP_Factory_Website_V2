(function initSignupAjax() {
    const signupModal = document.getElementById('signupModal');
    if (!signupModal) return;

    const form = signupModal.querySelector('form.auth-form');
    if (!form) return;

    // Root-cause fix for the double-submit: this form ALSO has a hardened
    // inline submit handler in views/landing/product_showcase.hbs. Binding a
    // second 'submit' listener here made BOTH fire a fetch on the same event
    // (preventDefault does not stop sibling listeners) → duplicate POST /signup.
    // When the inline handler owns the form, do NOT bind here.
    if (form.dataset.hardenedSignup === '1' || form.dataset.signupBound === '1') {
        return;
    }
    form.dataset.signupBound = '1';

    form.addEventListener('submit', async function (event) {
        event.preventDefault();
        event.stopImmediatePropagation();

        const submitBtn = form.querySelector('button[type="submit"]');
        if (submitBtn) {
            submitBtn.disabled = true;
            submitBtn.textContent = currentLanguage === 'tr' ? 'Yükleniyor...' : 'Loading...';
        }

        try {
            const formData = new FormData(form);
            const body = new URLSearchParams(formData).toString();

            const response = await fetch(form.action, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/x-www-form-urlencoded',
                    'Accept': 'application/json',
                    'X-Requested-With': 'XMLHttpRequest'
                },
                body,
                credentials: 'same-origin'
            });

            // Non-JSON redirect (signup success) — follow redirect
            if (response.redirected) {
                window.location.href = response.url;
                return;
            }

            // Try to parse JSON
            let data;
            try {
                data = await response.json();
            } catch (_) {
                // Server returned HTML (e.g. redirect after success)
                window.location.href = response.url || '/billing/checkout';
                return;
            }

            if (response.status === 409 && data.code === 'EMAIL_ALREADY_EXISTS') {
                // Close signup modal, show duplicate email popup
                const signupModalEl = document.getElementById('signupModal');
                if (signupModalEl) signupModalEl.style.display = 'none';
                document.body.style.overflow = 'auto';
                showEmailAlreadyExistsPopup(data);
                return;
            }

            if (!data.ok) {
                showSignupError(data.message_tr || data.message_en || (currentLanguage === 'tr' ? 'Bir hata oluştu.' : 'An error occurred.'));
                return;
            }

            // Success — redirect
            if (data.redirectUrl) {
                window.location.href = data.redirectUrl;
            } else {
                window.location.href = '/billing/checkout';
            }

        } catch (err) {
            console.error('[Signup] Fetch error:', err);
            // Do NOT native-submit as a fallback: it would create a second POST
            // (the AJAX one may already be in flight) and reintroduce duplicates.
            // The backend idempotency key + per-email lock are the safety net.
            showSignupError(currentLanguage === 'tr'
                ? 'Sunucuya ulaşılamadı. Lütfen tekrar deneyin.'
                : 'Could not reach the server. Please try again.');
        } finally {
            if (submitBtn) {
                submitBtn.disabled = false;
                submitBtn.textContent = getTranslation('signupCreateAccount');
            }
        }
    });

    function showSignupError(message) {
        let errEl = form.querySelector('.signup-ajax-error');
        if (!errEl) {
            errEl = document.createElement('div');
            errEl.className = 'signup-ajax-error';
            errEl.style.cssText = 'background:#fef2f2;border:1px solid #fecaca;border-radius:8px;padding:10px 14px;color:#dc2626;font-size:13px;margin-bottom:12px;';
            form.insertBefore(errEl, form.firstChild);
        }
        errEl.textContent = message;
        errEl.style.display = 'block';
    }
})();

