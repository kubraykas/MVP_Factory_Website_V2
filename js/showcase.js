function initializeMaturityForm() {
    const form = document.getElementById('maturityForm');
    if (!form || form.dataset.bound === '1') return;
    form.dataset.bound = '1';

    const feedback = document.getElementById('maturityFeedback');
    const submitBtn = document.getElementById('maturitySubmit');
    const MAIL = 'info@roket.digital';
    let inFlight = false;

    const t = (tr, en) => (currentLanguage === 'tr' ? tr : en);
    const labelOf = (input) => {
        const span = input && input.closest('label').querySelector(currentLanguage === 'tr' ? '.lang-tr' : '.lang-en');
        return span ? span.textContent.trim() : '';
    };
    const selectText = (name) => {
        const select = form.elements[name];
        const option = select && select.selectedOptions[0];
        return option && option.value ? option.textContent.trim() : '';
    };

    function syncOptionLabels() {
        form.querySelectorAll('option[data-tr]').forEach((option) => {
            option.textContent = option.getAttribute(currentLanguage === 'tr' ? 'data-tr' : 'data-en');
        });
    }
    syncOptionLabels();
    document.querySelectorAll('.lang-btn').forEach((button) => {
        button.addEventListener('click', function () { setTimeout(syncOptionLabels, 0); });
    });

    // Simple indicative level from the five answers (each 0–2, total 0–10)
    function indicativeLevel(score) {
        if (score <= 3) return t('Başlangıç', 'Beginning');
        if (score <= 7) return t('Gelişen', 'Developing');
        return t('İleri', 'Advanced');
    }

    function collect() {
        const fd = new FormData(form);
        const val = (k) => String(fd.get(k) || '').trim();
        const questions = Array.from(form.querySelectorAll('.maturity-question'));
        let score = 0;
        let answered = 0;
        const answerLines = questions.map((fieldset) => {
            const checked = fieldset.querySelector('input:checked');
            if (checked) { score += Number(checked.value); answered += 1; }
            const legend = fieldset.querySelector('legend ' + (currentLanguage === 'tr' ? '.lang-tr' : '.lang-en'));
            return '- ' + (legend ? legend.textContent.trim() : '') + ': ' + (checked ? labelOf(checked) : '—');
        });
        const priorities = Array.from(form.querySelectorAll('input[name="priorities"]:checked')).map(labelOf);
        const level = indicativeLevel(score);
        const comments = [
            t('DİJİTAL OLGUNLUK ANALİZİ TALEBİ', 'DIGITAL MATURITY ASSESSMENT REQUEST'),
            t('Sektör: ', 'Sector: ') + selectText('sector'),
            t('Ön gösterge: ', 'Indicative level: ') + level + ' (' + score + '/10)',
            '',
            t('Mevcut durum:', 'Current state:'),
            ...answerLines,
            '',
            t('Öncelikler: ', 'Priorities: ') + (priorities.join(', ') || '—'),
            t('Uygun görüşme zamanı: ', 'Preferred call time: ') + (selectText('preferredTime') || t('Fark etmez', 'No preference')),
            '',
            t('Not: ', 'Note: ') + (val('note') || '—')
        ].join('\n');
        return {
            payload: {
                _csrf: val('_csrf'),
                firstName: val('firstName'),
                lastName: val('lastName'),
                email: val('workEmail'),
                phone: val('phone'),
                jobTitle: val('jobTitle'),
                company: val('company'),
                companySize: val('companySize'),
                seatCount: '',
                comments,
                planName: 'Dijital Olgunluk Analizi',
                lang: currentLanguage
            },
            complete: answered === questions.length && Boolean(val('sector')) && Boolean(val('companySize')),
            consent: Boolean(fd.get('consent')),
            level
        };
    }

    function buildMailto(p, to) {
        const subject = t('Dijital Olgunluk Analizi Talebi — ', 'Digital Maturity Assessment Request — ') + p.company;
        const body = [
            t('Ad Soyad: ', 'Name: ') + p.firstName + ' ' + p.lastName,
            t('E-posta: ', 'E-mail: ') + p.email,
            t('Telefon: ', 'Phone: ') + p.phone,
            t('Unvan: ', 'Job title: ') + p.jobTitle,
            t('Şirket: ', 'Company: ') + p.company + ' (' + p.companySize + ')',
            '',
            p.comments
        ].join('\n');
        return 'mailto:' + MAIL + '?subject=' + encodeURIComponent(subject) + '&body=' + encodeURIComponent(body);
    }

    function show(kind, text, mailtoHref) {
        feedback.className = 'contact-feedback contact-feedback--' + kind;
        feedback.textContent = text;
        if (mailtoHref) {
            feedback.appendChild(document.createTextNode(' '));
            const a = document.createElement('a');
            a.href = mailtoHref;
            a.textContent = MAIL;
            feedback.appendChild(a);
        }
        feedback.hidden = false;
        feedback.scrollIntoView({ block: 'nearest' });
    }

    form.addEventListener('submit', async function (event) {
        event.preventDefault();
        if (inFlight) return;
        const { payload, complete, consent, level } = collect();
        if (!payload.firstName || !payload.lastName || !payload.email || !payload.company || !complete) {
            show('error', t('Lütfen yıldızlı alanları doldurun ve beş soruyu yanıtlayın.', 'Please fill in the starred fields and answer all five questions.'));
            return;
        }
        if (!consent) {
            show('error', t('Devam etmek için KVKK onayını işaretleyin.', 'Please tick the consent box to continue.'));
            return;
        }
        inFlight = true;
        const originalLabel = submitBtn.innerHTML;
        submitBtn.disabled = true;
        submitBtn.textContent = getTranslation('contactSending');
        feedback.hidden = true;
        try {
            const csrfMeta = document.querySelector('meta[name="csrf-token"]');
            const res = await fetch('/contact-sales', {
                method: 'POST',
                credentials: 'same-origin',
                headers: {
                    'Content-Type': 'application/json',
                    Accept: 'application/json',
                    'X-Requested-With': 'XMLHttpRequest',
                    'X-CSRF-Token': (csrfMeta && csrfMeta.content) || payload._csrf
                },
                body: JSON.stringify(payload)
            });
            const data = await res.json().catch(() => ({}));
            if (res.ok && data.ok) {
                show('ok', t('Teşekkürler. Yanıtlarınıza göre ön göstergeniz: ', 'Thank you. Based on your answers, your indicative level is: ')
                    + level + t('. Ekibimiz görüşme için en kısa sürede sizinle iletişime geçecek.', '. Our team will contact you shortly to schedule the call.'));
                form.reset();
            } else if (res.status === 400 && data.message) {
                show('error', data.message);
            } else {
                show('error', getTranslation('contactFailed'), buildMailto(payload, data.fallbackTo));
            }
        } catch (err) {
            show('error', getTranslation('contactFailed'), buildMailto(payload));
        } finally {
            inFlight = false;
            submitBtn.disabled = false;
            submitBtn.innerHTML = originalLabel;
        }
    });
}

function initializeEcosystemSizing() {
    const diagram = document.querySelector('.roket-image > .ecosystem-diagram');
    if (!diagram) return;
    const host = diagram.parentElement;
    // 640 includes the outer orbs and their maximum animated expansion.
    const resize = () => {
        const scale = Math.min(1.08, host.clientWidth / 640);
        host.style.setProperty('--ecosystem-scale', String(scale));
        host.style.setProperty('--ecosystem-height', `${640 * scale}px`);
    };
    resize();
    if (typeof ResizeObserver !== 'undefined') new ResizeObserver(resize).observe(host);
    else window.addEventListener('resize', resize);
}

