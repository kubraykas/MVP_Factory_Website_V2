// Enterprise "Contact Sales" → POST /contact-sales → info@roket.digital
// Başarısızlıkta mailto yedeği (konu + gövde önceden doldurulur).
// ──────────────────────────────────────────────────────────────
function initializeContactSalesForm() {
    const form = document.getElementById('contactSalesForm');
    if (!form || form.dataset.contactBound === '1') return;
    form.dataset.contactBound = '1';

    const feedback = document.getElementById('contactSalesFeedback');
    const submitBtn = document.getElementById('contactSalesSubmit');
    const mailtoLink = document.getElementById('contactSalesMailto');
    const ENTERPRISE_MAIL = 'info@roket.digital';
    let inFlight = false;

    function collect() {
        const fd = new FormData(form);
        const val = (k) => String(fd.get(k) || '').trim();
        return {
            _csrf: val('_csrf'),
            firstName: val('firstName'),
            lastName: val('lastName'),
            email: val('workEmail'),
            phone: val('phone'),
            jobTitle: val('jobTitle'),
            company: val('company'),
            companySize: val('companySize'),
            seatCount: val('seatCount'),
            comments: (window.schedMeeting ? window.schedMeeting + '\n\n' : '') + val('comments'),
            planName: val('planName') || 'Enterprise',
            lang: currentLanguage
        };
    }

    function buildMailto(p, to) {
        const slot = window.schedMeeting ? ' — ' + String(window.schedMeeting).split('\n')[0] : '';
        const subject = (currentLanguage === 'en'
            ? 'ROKET MVP Factory — Meeting Request'
            : 'ROKET MVP Factory — Görüşme Talebi') + slot;
        const lines = currentLanguage === 'en'
            ? ['Company: ' + p.company, 'Name: ' + p.firstName + ' ' + p.lastName, 'E-mail: ' + p.email,
               'Phone: ' + p.phone, 'Job title: ' + p.jobTitle, 'Company size: ' + p.companySize,
               'Expected users: ' + p.seatCount, 'Plan: ' + p.planName, '', 'Message:', p.comments]
            : ['Şirket: ' + p.company, 'Ad Soyad: ' + p.firstName + ' ' + p.lastName, 'E-posta: ' + p.email,
               'Telefon: ' + p.phone, 'Unvan: ' + p.jobTitle, 'Şirket büyüklüğü: ' + p.companySize,
               'Tahmini kullanıcı sayısı: ' + p.seatCount, 'Plan: ' + p.planName, '', 'Mesaj:', p.comments];
        return 'mailto:' + ENTERPRISE_MAIL + '?subject=' + encodeURIComponent(subject) + '&body=' + encodeURIComponent(lines.join('\n'));
    }

    function show(kind, text, mailtoHref) {
        if (!feedback) return;
        feedback.className = 'contact-feedback contact-feedback--' + kind;
        feedback.textContent = text;
        if (mailtoHref) {
            feedback.appendChild(document.createTextNode(' '));
            const a = document.createElement('a');
            a.href = mailtoHref;
            a.textContent = ENTERPRISE_MAIL;
            feedback.appendChild(a);
        }
        feedback.hidden = false;
        feedback.scrollIntoView({ block: 'nearest' });
    }

    // Doğrudan e-posta bağlantısı da forma göre önceden doldurulur
    form.addEventListener('input', function () {
        if (mailtoLink) mailtoLink.href = buildMailto(collect());
    });

    form.addEventListener('submit', async function (event) {
        event.preventDefault();
        if (inFlight) return;
        const payload = collect();
        if (!payload.firstName || !payload.lastName || !payload.email || !payload.company) {
            show('error', getTranslation('contactMissing'));
            return;
        }
        inFlight = true;
        const originalLabel = submitBtn ? submitBtn.textContent : '';
        if (submitBtn) { submitBtn.disabled = true; submitBtn.textContent = getTranslation('contactSending'); }
        if (feedback) feedback.hidden = true;
        try {
            const csrfMeta = document.querySelector('meta[name="csrf-token"]');
            const res = await fetch('/contact-sales', {
                method: 'POST',
                credentials: 'same-origin',
                headers: {
                    'Content-Type': 'application/json',
                    Accept: 'application/json',
                    'X-Requested-With': 'XMLHttpRequest',
                    'X-CSRF-Token': (csrfMeta && csrfMeta.content) || payload._csrf
                },
                body: JSON.stringify(payload)
            });
            const data = await res.json().catch(() => ({}));
            if (res.ok && data.ok) {
                show('ok', getTranslation('contactSuccess'));
                form.reset();
                if (mailtoLink) mailtoLink.href = buildMailto(collect(), data.to);
            } else if (res.status === 400 && data.message) {
                show('error', data.message);
            } else {
                show('error', getTranslation('contactFailed'), buildMailto(payload, data.fallbackTo));
            }
        } catch (err) {
            show('error', getTranslation('contactFailed'), buildMailto(payload));
        } finally {
            inFlight = false;
            if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = originalLabel || getTranslation('contactSubmit'); }
        }
    });
}


