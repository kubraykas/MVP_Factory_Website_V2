let currentLanguage = 'tr';

window.setLanguage = function(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        }
    });
    
    updatePageText();
};

function getTranslation(key) {
    return translations[currentLanguage][key] || key;
}

function updatePageText() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const text = getTranslation(key);
        // a few strings (hero slogan) carry markup: render those as HTML
        if (/<span/.test(text)) element.innerHTML = text;
        else element.textContent = text;
    });
    
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
        const key = element.getAttribute('data-i18n-html');
        element.innerHTML = getTranslation(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        const value = getTranslation(key);
        if (value && value !== key) {
            element.setAttribute('placeholder', value);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(element => {
        const key = element.getAttribute('data-i18n-title');
        const value = getTranslation(key);
        if (value && value !== key) {
            element.setAttribute('title', value);
        }
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
        const key = element.getAttribute('data-i18n-aria-label');
        const value = getTranslation(key);
        if (value && value !== key) {
            element.setAttribute('aria-label', value);
        }
    });

    document.querySelectorAll('.lang-tr').forEach((element) => {
        element.style.display = currentLanguage === 'tr' ? '' : 'none';
    });

    document.querySelectorAll('.lang-en').forEach((element) => {
        element.style.display = currentLanguage === 'en' ? '' : 'none';
    });
}

